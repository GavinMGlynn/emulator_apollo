ap_m68040_move_timing_t
ap_m68040_move_timing(ap_m68040_move_source_t source,
                      ap_m68040_move_destination_t destination) {
  if (source >= AP_M68040_MOVE_SRC_COUNT ||
      destination >= AP_M68040_MOVE_DST_COUNT) {
    return (ap_m68040_move_timing_t){0};
  }
  return table[destination][source];
}

bool ap_m68040_move_source_is_indexed(ap_m68040_move_source_t source) {
  return source >= AP_M68040_MOVE_SRC_INDEXED &&
         source < AP_M68040_MOVE_SRC_COUNT;
}
