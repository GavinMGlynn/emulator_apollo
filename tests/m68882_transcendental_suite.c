static void test_the_manual_has_atanhs_poles_the_wrong_way_round(void) {
  /* The one manual defect in this work that is **corrected** rather than
   * transcribed, and the reasoning is why.
   *
   * Page 4-26's description of `FATANH` reads: "the result is equal to
   * -infinity or +infinity if the source is equal to +1 or -1, respectively".
   * Read as written, `atanh(+1)` is a *negative* infinity.
   *
   * It cannot be. `atanh` is odd and strictly increasing on `(-1, +1)`, and
   * `atanh(x) = (1/2) ln((1+x)/(1-x))` -- whose numerator grows and denominator
   * vanishes as `x` rises to one. `atanh(+1)` is `+infinity`. The same page's
   * exception byte and operation table are both consistent with that; only the
   * sentence is transposed.
   *
   * Every other suspect entry in this project is transcribed as printed,
   * because proving a figure wrong is not the same as knowing its value. Here
   * it is: the mathematics does not merely refute the printed text, it supplies
   * the unique replacement, since there is no third way to assign two signs to
   * two arguments. That is the standing rule's second half satisfied for the
   * first time, and it is the only reason this one is changed. */
  const ap_m68882_extended_t one = {false, AP_M68882_BIAS_EXTENDED,
                                    0x8000000000000000ULL};
  ap_m68882_extended_t minus_one = one;
  minus_one.sign = true;

  const ap_m68882_op_t at_plus =
      ap_m68882_atanh(&one, AP_M68882_ROUND_NEAREST,
                      AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT(AP_M68882_TYPE_INFINITY,
                        ap_m68882_classify(&at_plus.value));
  TEST_ASSERT_FALSE_MESSAGE(at_plus.value.sign,
                            "atanh(+1) is a positive infinity");

  const ap_m68882_op_t at_minus =
      ap_m68882_atanh(&minus_one, AP_M68882_ROUND_NEAREST,
                      AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT(AP_M68882_TYPE_INFINITY,
                        ap_m68882_classify(&at_minus.value));
  TEST_ASSERT_TRUE_MESSAGE(at_minus.value.sign,
                           "atanh(-1) is a negative infinity");

  /* The exception is the same either way -- "set if the source is equal to +1
   * or -1" -- so only the sign of the result was ever at issue. */
  TEST_ASSERT_NOT_EQUAL_UINT(0u, at_plus.exceptions & (1u << AP_M68882_EXC_DZ));
  TEST_ASSERT_NOT_EQUAL_UINT(0u,
                             at_minus.exceptions & (1u << AP_M68882_EXC_DZ));
  TEST_ASSERT_EQUAL_UINT(0u,
                         at_plus.exceptions & (1u << AP_M68882_EXC_OPERR));

  /* And the function really is increasing on the way there, which is the
   * property the printed text violates. */
  const ap_m68882_extended_t near = {false, AP_M68882_BIAS_EXTENDED - 1,
                                     0xFF00000000000000ULL};
  const ap_m68882_op_t inside = ap_m68882_atanh(
      &near, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_FALSE_MESSAGE(inside.value.sign,
                            "atanh of a positive argument is positive");
}

static void test_the_hyperbolic_domain_and_limits(void) {
  /* `FSINH`, `FCOSH` and `FTANH` have `OPERR` cleared: every real argument is
   * in range and an infinity is a limit. Their limits differ, and each comes
   * from its own operation table -- `sinh` goes to an infinity keeping the
   * sign, `cosh` to `+inf` for both signs because it is even, and `tanh` to
   * `+/-1.0` rather than to an infinity at all. */
  const ap_m68882_extended_t plus = {false, 0x7FFFu, 0u};
  const ap_m68882_extended_t minus = {true, 0x7FFFu, 0u};

  const ap_m68882_op_t sinh_up =
      ap_m68882_sinh(&plus, AP_M68882_ROUND_NEAREST,
                     AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT(AP_M68882_TYPE_INFINITY,
                        ap_m68882_classify(&sinh_up.value));
  TEST_ASSERT_FALSE(sinh_up.value.sign);
  const ap_m68882_op_t sinh_down =
      ap_m68882_sinh(&minus, AP_M68882_ROUND_NEAREST,
                     AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_TRUE(sinh_down.value.sign);

  for (unsigned s = 0; s < 2u; s++) {
    const ap_m68882_op_t even =
        ap_m68882_cosh(s ? &minus : &plus, AP_M68882_ROUND_NEAREST,
                       AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_EQUAL_INT(AP_M68882_TYPE_INFINITY,
                          ap_m68882_classify(&even.value));
    TEST_ASSERT_FALSE_MESSAGE(even.value.sign,
                              "cosh is even, so both infinities go up");
    TEST_ASSERT_EQUAL_UINT(0u, even.exceptions & (1u << AP_M68882_EXC_OPERR));

    const ap_m68882_op_t bounded =
        ap_m68882_tanh(s ? &minus : &plus, AP_M68882_ROUND_NEAREST,
                       AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_EQUAL_UINT_MESSAGE(AP_M68882_BIAS_EXTENDED,
                                   bounded.value.exponent,
                                   "tanh of an infinity is one, not infinity");
    TEST_ASSERT_EQUAL_UINT64(0x8000000000000000ULL, bounded.value.mantissa);
    TEST_ASSERT_EQUAL(s != 0u, bounded.value.sign);
  }

  /* `FATANH` is the only one of the four with a domain error. */
  const ap_m68882_extended_t over = {false, AP_M68882_BIAS_EXTENDED,
                                     0x8000000000000001ULL};
  const ap_m68882_op_t outside = ap_m68882_atanh(
      &over, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT(AP_M68882_TYPE_NAN,
                        ap_m68882_classify(&outside.value));
  TEST_ASSERT_NOT_EQUAL_UINT(0u,
                             outside.exceptions & (1u << AP_M68882_EXC_OPERR));
  const ap_m68882_op_t at_infinity = ap_m68882_atanh(
      &plus, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT(AP_M68882_TYPE_NAN,
                        ap_m68882_classify(&at_infinity.value));
  TEST_ASSERT_NOT_EQUAL_UINT(
      0u, at_infinity.exceptions & (1u << AP_M68882_EXC_OPERR));
}

static void test_sinh_and_atanh_keep_their_bits_near_zero(void) {
  /* Both are written in the form that does not cancel, and this is the check
   * that it worked. For a tiny argument `sinh(x)` and `atanh(x)` are both `x`
   * to within a unit in the last place -- so an implementation that formed
   * `(e^x - e^-x)/2` or `ln((1+x)/(1-x))/2` directly would return something
   * with most of its significand gone, and the failure would look like a
   * plausible small number rather than an obvious wrong one. */
  const ap_m68882_extended_t tiny = {false, AP_M68882_BIAS_EXTENDED - 60,
                                     0xC000000000000000ULL};
  const ap_m68882_op_t s = ap_m68882_sinh(&tiny, AP_M68882_ROUND_NEAREST,
                                          AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_UINT(tiny.exponent, s.value.exponent);
  TEST_ASSERT_EQUAL_UINT64(tiny.mantissa, s.value.mantissa);

  const ap_m68882_op_t a = ap_m68882_atanh(&tiny, AP_M68882_ROUND_NEAREST,
                                           AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_UINT(tiny.exponent, a.value.exponent);
  TEST_ASSERT_EQUAL_UINT64(tiny.mantissa, a.value.mantissa);

  /* `cosh` of the same argument is one, which is the correct rounding and not
   * a lost result: it differs from one by about `2^-121`. */
  const ap_m68882_op_t c = ap_m68882_cosh(&tiny, AP_M68882_ROUND_NEAREST,
                                          AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_UINT(AP_M68882_BIAS_EXTENDED, c.value.exponent);
  TEST_ASSERT_EQUAL_UINT64(0x8000000000000000ULL, c.value.mantissa);
}

/* Order two finite extended values: -1, 0 or +1. Used by the rounding-mode
 * tests, where what matters is which side of the true result each mode lands
 * on rather than the distance. */
static int compare_extended(ap_m68882_extended_t a, ap_m68882_extended_t b) {
  const bool a_zero = a.mantissa == 0u && a.exponent == 0u;
  const bool b_zero = b.mantissa == 0u && b.exponent == 0u;
  if (a_zero && b_zero) return 0;
  if (a.sign != b.sign) return a.sign ? -1 : 1;
  int order;
  if (a.exponent != b.exponent) {
    order = a.exponent < b.exponent ? -1 : 1;
  } else if (a.mantissa != b.mantissa) {
    order = a.mantissa < b.mantissa ? -1 : 1;
  } else {
    return 0;
  }
  return a.sign ? -order : order;
}

typedef ap_m68882_op_t (*unary_fn_t)(const ap_m68882_extended_t *,
                                     ap_m68882_rounding_t,
                                     ap_m68882_precision_t);

static const unary_fn_t every_transcendental[] = {
    ap_m68882_etox,  ap_m68882_etoxm1, ap_m68882_twotox, ap_m68882_tentox,
    ap_m68882_logn,  ap_m68882_lognp1, ap_m68882_log2,   ap_m68882_log10,
    ap_m68882_sin,   ap_m68882_cos,    ap_m68882_tan,    ap_m68882_atan,
    ap_m68882_asin,  ap_m68882_acos,   ap_m68882_sinh,   ap_m68882_cosh,
    ap_m68882_tanh,  ap_m68882_atanh};

#define EVERY_COUNT (sizeof every_transcendental / sizeof every_transcendental[0])

static void test_every_transcendental_honours_every_rounding_mode(void) {
  /* The 68882 item's own verification asks for "each operation and rounding
   * mode", and until this test the whole family had only ever been measured at
   * round-to-nearest. It is the check that the FPCR's mode reaches the result
   * at all.
   *
   * The invariant is ordering rather than distance: whatever the true value,
   * rounding toward minus infinity cannot land above rounding toward plus
   * infinity, and round-to-zero cannot exceed either in magnitude. An
   * implementation that ignored the mode would return the same value four
   * times and satisfy the weak inequalities -- so the count of arguments where
   * the modes genuinely *differ* is asserted too.
   *
   * Single precision is used because that is where the mode has bits to act
   * on; see the next test for why extended is different. */
  const ap_m68882_extended_t argument = {false, AP_M68882_BIAS_EXTENDED - 2,
                                         0xC90FDAA22168C235ULL};
  unsigned differing = 0;
  for (unsigned i = 0; i < EVERY_COUNT; i++) {
    const ap_m68882_extended_t down =
        every_transcendental[i](&argument, AP_M68882_ROUND_MINUS_INFINITY,
                                AP_M68882_PRECISION_SINGLE)
            .value;
    const ap_m68882_extended_t up =
        every_transcendental[i](&argument, AP_M68882_ROUND_PLUS_INFINITY,
                                AP_M68882_PRECISION_SINGLE)
            .value;
    const ap_m68882_extended_t near =
        every_transcendental[i](&argument, AP_M68882_ROUND_NEAREST,
                                AP_M68882_PRECISION_SINGLE)
            .value;
    const ap_m68882_extended_t zero =
        every_transcendental[i](&argument, AP_M68882_ROUND_ZERO,
                                AP_M68882_PRECISION_SINGLE)
            .value;

    TEST_ASSERT_TRUE_MESSAGE(compare_extended(down, up) <= 0,
                             "rounding down landed above rounding up");
    TEST_ASSERT_TRUE_MESSAGE(compare_extended(down, near) <= 0,
                             "rounding down landed above nearest");
    TEST_ASSERT_TRUE_MESSAGE(compare_extended(near, up) <= 0,
                             "nearest landed above rounding up");
    /* Round-to-zero is one of the two directed modes depending on the sign. */
    TEST_ASSERT_TRUE_MESSAGE(
        compare_extended(zero, zero.sign ? down : up) *
                (zero.sign ? -1 : 1) <=
            0,
        "round to zero ran away from zero");
    if (compare_extended(down, up) != 0) {
      differing++;
    }
  }
  TEST_ASSERT_TRUE_MESSAGE(
      differing >= EVERY_COUNT - 2u,
      "almost every transcendental should be inexact at this argument");
}

static void test_the_mode_is_a_no_op_where_there_is_nothing_left_to_round(void) {
  /* A documented approximation, recorded because it is invisible otherwise.
   *
   * The part computes internally at 67 bits and rounds to the destination with
   * the FPCR mode, so for an *extended* destination the directed modes give
   * three different answers. This model computes a 64-bit approximation
   * directly -- every intermediate rounds to nearest at the destination's own
   * width -- so there are no bits below it left to round, and at extended
   * precision all four modes return the same value.
   *
   * The divergence is at most one unit in the last place, which is a
   * sixty-fourth of §4.3.2's typical bound and a four-thousandth of its worst
   * case, so it is far inside the interval the manual guarantees. Closing it
   * would mean carrying guard bits through every kernel -- and the part's own
   * directed rounding of a transcendental is only accurate to the same
   * published bound, so the gain would be smaller than it looks.
   *
   * Asserted rather than merely written down, so that anyone who later adds
   * guard bits finds this test and deletes it deliberately. */
  const ap_m68882_extended_t argument = {false, AP_M68882_BIAS_EXTENDED,
                                         0x8000000000000000ULL};
  for (unsigned i = 0; i < EVERY_COUNT; i++) {
    const ap_m68882_extended_t near =
        every_transcendental[i](&argument, AP_M68882_ROUND_NEAREST,
                                AP_M68882_PRECISION_EXTENDED)
            .value;
    for (unsigned m = 0; m < 4u; m++) {
      const ap_m68882_extended_t other =
          every_transcendental[i](&argument, (ap_m68882_rounding_t)m,
                                  AP_M68882_PRECISION_EXTENDED)
              .value;
      TEST_ASSERT_EQUAL_UINT_MESSAGE(near.exponent, other.exponent,
                                     "extended rounding should be a no-op");
      TEST_ASSERT_EQUAL_UINT64(near.mantissa, other.mantissa);
    }
  }
}

static void test_an_overflowing_transcendental_follows_6_1_4(void) {
  /* §6.1.4's trap-disabled table, reached through a transcendental rather than
   * an arithmetic operation -- the two paths substitute the result separately,
   * so both need checking:
   *
   *     RN   Infinity, with the sign of the intermediate result
   *     RZ   Largest magnitude number, with that sign
   *     RM   positive overflow -> largest positive; negative -> -infinity
   *     RP   positive overflow -> +infinity;        negative -> largest negative
   *
   * The exception byte is identical in all four cases, which is exactly why
   * getting the value wrong is silent: a program sees `OVFL` either way and
   * only the stored number differs. */
  const ap_m68882_extended_t big = {false, AP_M68882_BIAS_EXTENDED + 14,
                                    0x9C40000000000000ULL}; /* 20000 */
  const struct {
    ap_m68882_rounding_t mode;
    bool infinite;
  } expectation[] = {{AP_M68882_ROUND_NEAREST, true},
                     {AP_M68882_ROUND_ZERO, false},
                     {AP_M68882_ROUND_MINUS_INFINITY, false},
                     {AP_M68882_ROUND_PLUS_INFINITY, true}};
  for (unsigned i = 0; i < 4u; i++) {
    const ap_m68882_op_t got =
        ap_m68882_etox(&big, expectation[i].mode, AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_NOT_EQUAL_UINT_MESSAGE(
        0u, got.exceptions & (1u << AP_M68882_EXC_OVFL),
        "an overflow must be reported whatever the mode");
    if (expectation[i].infinite) {
      TEST_ASSERT_EQUAL_INT_MESSAGE(AP_M68882_TYPE_INFINITY,
                                    ap_m68882_classify(&got.value),
                                    "this mode overflows to an infinity");
    } else {
      TEST_ASSERT_EQUAL_INT_MESSAGE(AP_M68882_TYPE_NORMALIZED,
                                    ap_m68882_classify(&got.value),
                                    "this mode overflows to a finite number");
      TEST_ASSERT_EQUAL_UINT(0x7FFEu, got.value.exponent);
      TEST_ASSERT_EQUAL_UINT64(0xFFFFFFFFFFFFFFFFULL, got.value.mantissa);
    }
    TEST_ASSERT_FALSE(got.value.sign);
  }

  /* The negative direction, where `RM` and `RP` swap roles. `sinh` is odd, so
   * a large negative argument overflows downward. */
  ap_m68882_extended_t negative = big;
  negative.sign = true;
  const ap_m68882_op_t down =
      ap_m68882_sinh(&negative, AP_M68882_ROUND_MINUS_INFINITY,
                     AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT_MESSAGE(AP_M68882_TYPE_INFINITY,
                                ap_m68882_classify(&down.value),
                                "a negative overflow runs away under RM");
  TEST_ASSERT_TRUE(down.value.sign);
  const ap_m68882_op_t held =
      ap_m68882_sinh(&negative, AP_M68882_ROUND_PLUS_INFINITY,
                     AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_INT_MESSAGE(AP_M68882_TYPE_NORMALIZED,
                                ap_m68882_classify(&held.value),
                                "RP holds a negative overflow finite");
  TEST_ASSERT_TRUE(held.value.sign);
}

/* ---------------------------------------------------------------------------
 * Bit-exact determinism across build types and platforms.
 * ------------------------------------------------------------------------- */

/* FNV-1a over the raw result, so a single constant covers every function.
 *
 * The accuracy sweeps above assert a *bound*, which is what §4.3.2 specifies --
 * but a bound is exactly what a build-type difference can hide inside. A result
 * that moved by one unit in the last place between `-O0` and `-O3` would pass
 * every one of them, and would mean the core's output depended on which
 * compiler flags built it.
 *
 * CI asserts that emulated results are identical at `-O0` and `-O3` and on four
 * platforms, and it does so by comparing each build against a committed golden.
 * The probe golden covers the integer core and has no floating-point entry at
 * all, so until this test the nineteen transcendentals sat outside that
 * guarantee. This is their golden: one number over the whole family, checked in
 * every build and on every platform the suite runs on.
 *
 * Everything it feeds in is derived arithmetically rather than drawn from a
 * generator, so the argument set is part of the source and not a seed. */
static uint64_t digest_step(uint64_t hash, uint64_t value) {
  for (unsigned byte = 0; byte < 8u; byte++) {
    hash ^= (value >> (byte * 8u)) & 0xFFu;
    hash *= 0x100000001B3ULL;
  }
  return hash;
}

static uint64_t digest_result(uint64_t hash, ap_m68882_op_t r) {
  hash = digest_step(hash, r.value.sign ? 1u : 0u);
  hash = digest_step(hash, r.value.exponent);
  hash = digest_step(hash, r.value.mantissa);
  return digest_step(hash, r.exceptions);
}

static void test_the_family_is_bit_identical_in_every_build(void) {
  uint64_t hash = 0xCBF29CE484222325ULL;

  /* A deterministic spread: exponents across the whole range and a mantissa
   * that walks its own bits, so no function is exercised only near one. */
  for (int e = -60; e <= 60; e += 7) {
    uint64_t mantissa = 0x8000000000000000ULL;
    for (unsigned step = 0; step < 5u; step++) {
      mantissa ^= (uint64_t)0x9E3779B97F4A7C15ULL >> step;
      mantissa |= 0x8000000000000000ULL;
      for (unsigned negative = 0; negative < 2u; negative++) {
        const ap_m68882_extended_t x = {
            negative != 0u, (uint16_t)(AP_M68882_BIAS_EXTENDED + e), mantissa};
        for (unsigned i = 0; i < EVERY_COUNT; i++) {
          for (unsigned mode = 0; mode < 4u; mode++) {
            for (unsigned precision = 0; precision < 3u; precision++) {
              static const ap_m68882_precision_t widths[3] = {
                  AP_M68882_PRECISION_EXTENDED, AP_M68882_PRECISION_SINGLE,
                  AP_M68882_PRECISION_DOUBLE};
              hash = digest_result(
                  hash, every_transcendental[i](
                            &x, (ap_m68882_rounding_t)mode, widths[precision]));
            }
          }
        }
      }
    }
  }

  /* `FSINCOS` writes two results and so cannot go through the table above; its
   * cosine would otherwise never be hashed. */
  for (int e = -8; e <= 8; e += 4) {
    const ap_m68882_extended_t x = {false,
                                    (uint16_t)(AP_M68882_BIAS_EXTENDED + e),
                                    0xC90FDAA22168C235ULL};
    ap_m68882_op_t sine, cosine;
    ap_m68882_sincos(&x, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED,
                     &sine, &cosine);
    hash = digest_result(hash, sine);
    hash = digest_result(hash, cosine);
  }

  TEST_ASSERT_EQUAL_HEX64_MESSAGE(
      0xDFE1312935332E88ULL, hash,
      "the transcendental family changed, or this build is not bit-identical "
      "to the one this golden was taken from");
}

static void test_a_denormal_argument_survives_every_function(void) {
  /* Denormals are where an implementation with reductions in it breaks, and all
   * nineteen of these have reductions. For an argument this small every one of
   * them has a first-order answer that is either the argument itself, one, or
   * a large logarithm -- and *none* of them is zero.
   *
   * Four separate faults were found here, each hidden by the fact that a wrong
   * answer near zero still looks like a small number:
   *
   *   - `FMUL` and `FDIV` denormalised at the minimum exponent, which is legal,
   *     so every result there came back halved. That was a core arithmetic bug,
   *     not a transcendental one, and it moved most of this family.
   *   - `nx_scale2` flushed a halved denormal to zero instead of denormalising
   *     it, which cost `FSINH` and `FATANH` their whole answer.
   *   - `FLOGNP1` tested the exponent *field* for its small-argument path, so a
   *     denormal -- whose field is zero -- was excluded from the very path that
   *     exists for small arguments and sent through `1 + x`, where it vanished.
   *   - `FATAN` halves its argument before the series, and halving the smallest
   *     denormal gives zero, which the doubling afterwards cannot undo.
   *
   * The accuracy sweeps could not have found any of them: their vectors are
   * normal numbers, because an expectation generated at the bottom of the
   * exponent range is dominated by the denormalisation rather than by the
   * function. */
  const ap_m68882_extended_t smallest = {false, 0u, 1u};
  const ap_m68882_extended_t middling = {false, 0u, 0x4000000000000000ULL};

  /* These return their argument to first order: every series here begins with
   * its linear term. */
  const unary_fn_t identity_like[] = {ap_m68882_etoxm1, ap_m68882_lognp1,
                                      ap_m68882_sin,    ap_m68882_tan,
                                      ap_m68882_atan,   ap_m68882_asin,
                                      ap_m68882_sinh,   ap_m68882_tanh,
                                      ap_m68882_atanh};
  for (unsigned i = 0; i < sizeof identity_like / sizeof identity_like[0];
       i++) {
    for (unsigned which = 0; which < 2u; which++) {
      const ap_m68882_extended_t *x = which ? &middling : &smallest;
      const ap_m68882_op_t got = identity_like[i](
          x, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
      TEST_ASSERT_EQUAL_UINT_MESSAGE(x->exponent, got.value.exponent,
                                     "a denormal argument lost its exponent");
      TEST_ASSERT_EQUAL_UINT64_MESSAGE(
          x->mantissa, got.value.mantissa,
          "a denormal argument should come back unchanged to first order");
    }
  }

  /* These return one: `e^x`, `2^x`, `10^x` and `cosh x` are all `1 + O(x)`. */
  const unary_fn_t one_like[] = {ap_m68882_etox, ap_m68882_twotox,
                                 ap_m68882_tentox, ap_m68882_cos,
                                 ap_m68882_cosh};
  for (unsigned i = 0; i < sizeof one_like / sizeof one_like[0]; i++) {
    const ap_m68882_op_t got = one_like[i](&middling, AP_M68882_ROUND_NEAREST,
                                           AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_EQUAL_UINT(AP_M68882_BIAS_EXTENDED, got.value.exponent);
    TEST_ASSERT_EQUAL_UINT64(0x8000000000000000ULL, got.value.mantissa);
  }

  /* `acos` of anything that small is `pi/2`. */
  const ap_m68882_op_t arc = ap_m68882_acos(&middling, AP_M68882_ROUND_NEAREST,
                                            AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_UINT(AP_M68882_BIAS_EXTENDED, arc.value.exponent);
  TEST_ASSERT_EQUAL_UINT64(0xC90FDAA22168C235ULL, arc.value.mantissa);

  /* And the logarithms give a large negative number rather than a NAN: a
   * denormal is a perfectly ordinary positive value to them, and the reduction
   * normalises it before walking the significand. */
  const unary_fn_t log_like[] = {ap_m68882_logn, ap_m68882_log2,
                                 ap_m68882_log10};
  for (unsigned i = 0; i < 3u; i++) {
    const ap_m68882_op_t got = log_like[i](&smallest, AP_M68882_ROUND_NEAREST,
                                           AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_EQUAL_INT_MESSAGE(AP_M68882_TYPE_NORMALIZED,
                                  ap_m68882_classify(&got.value),
                                  "the logarithm of a denormal is finite");
    TEST_ASSERT_TRUE_MESSAGE(got.value.sign,
                             "the logarithm of a tiny value is negative");
    /* `log2(2^-16445)` is about -16445, so the exponent is 14. */
    TEST_ASSERT_TRUE(got.value.exponent >= AP_M68882_BIAS_EXTENDED + 11);
    TEST_ASSERT_TRUE(got.value.exponent <= AP_M68882_BIAS_EXTENDED + 14);
  }
}

static void test_a_nan_argument_comes_back_with_its_payload(void) {
  /* §4.5.4 opens by saying the operation tables carry no NAN row "because NANs
   * are handled the same way in all operations" -- and the transcendentals are
   * operations. Then: "if either, but not both, operand of an operation is a
   * NAN, and it is a non-signaling NAN, then **that NAN is returned as the
   * result**."
   *
   * So the payload and the sign survive. That is the whole point of a payload:
   * it says where the trouble started, and a function that substituted its own
   * would erase that at the first transcendental in a chain -- turning a
   * traceable NAN into an anonymous one, silently, because both still classify
   * as NANs and every existing test was satisfied by that.
   *
   * `FADD` had this right and the nineteen did not; they returned a fixed
   * pattern with a cleared sign. The comparison against `FADD` is the assertion
   * that matters, since §4.5.4's claim is precisely that the two behave
   * alike. */
  const ap_m68882_extended_t payload = {true, 0x7FFFu, 0xDEADBEEFCAFEF00DULL};
  const ap_m68882_extended_t one = {false, AP_M68882_BIAS_EXTENDED,
                                    0x8000000000000000ULL};
  const ap_m68882_op_t reference =
      ap_m68882_add(&payload, &one, AP_M68882_ROUND_NEAREST,
                    AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_UINT64(payload.mantissa, reference.value.mantissa);

  for (unsigned i = 0; i < EVERY_COUNT; i++) {
    const ap_m68882_op_t got = every_transcendental[i](
        &payload, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_EQUAL_UINT64_MESSAGE(reference.value.mantissa,
                                     got.value.mantissa,
                                     "a transcendental lost the NAN payload");
    TEST_ASSERT_EQUAL_MESSAGE(reference.value.sign, got.value.sign,
                              "a transcendental lost the NAN sign");
    TEST_ASSERT_EQUAL_UINT_MESSAGE(
        0u, got.exceptions & (1u << AP_M68882_EXC_SNAN),
        "a quiet NAN raises nothing");
  }

  /* `FSINCOS` writes two results and both must carry it. */
  ap_m68882_op_t sine, cosine;
  ap_m68882_sincos(&payload, AP_M68882_ROUND_NEAREST,
                   AP_M68882_PRECISION_EXTENDED, &sine, &cosine);
  TEST_ASSERT_EQUAL_UINT64(payload.mantissa, sine.value.mantissa);
  TEST_ASSERT_EQUAL_UINT64(payload.mantissa, cosine.value.mantissa);
}

static void test_a_signalling_nan_is_quietened_the_same_way_everywhere(void) {
  /* §4.5.4.2: "the SNAN is converted to a non-signaling NAN (by setting the
   * SNAN bit in the operand to a one), and the operation continues as described
   * in the preceding section for non-signaling NANs."
   *
   * So it is the *same value* with one bit set, not a fresh NAN -- the payload
   * survives being quietened. And it is raised once: the result is no longer
   * signalling, so a chain of operations reports one exception rather than one
   * per instruction. */
  const ap_m68882_extended_t signalling = {false, 0x7FFFu,
                                           0x2000000000000001ULL};
  const ap_m68882_extended_t one = {false, AP_M68882_BIAS_EXTENDED,
                                    0x8000000000000000ULL};
  const ap_m68882_op_t reference =
      ap_m68882_add(&signalling, &one, AP_M68882_ROUND_NEAREST,
                    AP_M68882_PRECISION_EXTENDED);

  for (unsigned i = 0; i < EVERY_COUNT; i++) {
    const ap_m68882_op_t got = every_transcendental[i](
        &signalling, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
    TEST_ASSERT_EQUAL_UINT64_MESSAGE(
        reference.value.mantissa, got.value.mantissa,
        "quietening must match the arithmetic's, bit for bit");
    TEST_ASSERT_NOT_EQUAL_UINT_MESSAGE(
        0u, got.exceptions & (1u << AP_M68882_EXC_SNAN),
        "a signalling NAN must raise SNAN");
    TEST_ASSERT_FALSE_MESSAGE(ap_m68882_is_signalling_nan(&got.value),
                              "the result must not still be signalling");
    /* The low bits of the payload are untouched by quietening. */
    TEST_ASSERT_EQUAL_UINT64(signalling.mantissa & 0xFFFFFFFFULL,
                             got.value.mantissa & 0xFFFFFFFFULL);
  }
}

static void test_cosh_never_reports_an_underflow_it_did_not_have(void) {
  /* `cosh` is never less than one, so it cannot underflow -- but it forms
   * `e^-|x|`, which underflows for any large argument. Collecting that made
   * `FCOSH` report `UNFL` on a result of several thousand.
   *
   * §6.1.5 defines underflow by "the intermediate result of an arithmetic
   * operation ... too small to be represented", meaning the *operation's* own
   * result. An exception raised for a step the caller cannot see is worse than
   * none: a handler traps on an answer that is perfectly representable, and
   * nothing in the value hints at why. */
  const ap_m68882_extended_t big = {false, AP_M68882_BIAS_EXTENDED + 9,
                                    0xFA00000000000000ULL}; /* 1000 */
  const ap_m68882_op_t got = ap_m68882_cosh(
      &big, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_TRUE_MESSAGE(got.value.exponent > AP_M68882_BIAS_EXTENDED,
                           "cosh of a large argument is large");
  TEST_ASSERT_EQUAL_UINT_MESSAGE(
      0u, got.exceptions & (1u << AP_M68882_EXC_UNFL),
      "cosh cannot underflow: its own e^-|x| did, and that is not the result");

  /* `sinh` reaches the same path and is equally incapable of underflowing
   * there: it uses the direct difference only for `|x| >= 1`, where the answer
   * is at least 1.17. */
  const ap_m68882_op_t hyperbolic = ap_m68882_sinh(
      &big, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_EXTENDED);
  TEST_ASSERT_EQUAL_UINT(0u,
                         hyperbolic.exceptions & (1u << AP_M68882_EXC_UNFL));

  /* An exponential that genuinely does become too small still reports it. */
  ap_m68882_extended_t negative = big;
  negative.sign = true;
  const ap_m68882_op_t real = ap_m68882_etox(
      &negative, AP_M68882_ROUND_NEAREST, AP_M68882_PRECISION_SINGLE);
  TEST_ASSERT_NOT_EQUAL_UINT_MESSAGE(
      0u, real.exceptions & (1u << AP_M68882_EXC_UNFL),
      "a genuine underflow must still be reported");
}

